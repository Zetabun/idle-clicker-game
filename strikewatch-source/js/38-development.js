  const PLAYER_XP_BASE = 72;
  const PLAYER_XP_GROWTH = 34;
  const TRAINING_PROGRESS_TARGET = 100;
  const TEAM_BENEFIT_MAX = 5;
  const CASH_STORE_PURCHASE_LOCK_MS = 900;
  const CASH_STORE_PURCHASE_FEEDBACK_MS = 4200;

  // Store purchases are synchronous, but the Supply Depot is rendered from
  // state-derived HTML. Keep a short-lived UI receipt so the freshly rendered
