  function normaliseTeamBenefits(raw) {
    return Object.fromEntries(Object.keys(TEAM_BENEFIT_DEFS).map(id => [
      id,
      clamp(Math.round(Number(raw?.[id]) || 0), 0, TEAM_BENEFIT_MAX)
    ]));
  }

  function teamBenefitLevel(id) {
    return clamp(Math.round(Number(careerState.teamBenefits?.[id]) || 0), 0, TEAM_BENEFIT_MAX);
  }

  function teamTrainingMultiplier() {
    const infrastructure = typeof clubInfrastructureTrainingMultiplier === 'function' ? clubInfrastructureTrainingMultiplier() : 1;
    return (1 + teamBenefitLevel('coaching') * 0.08) * infrastructure;
  }

  function teamPlayerXpMultiplier() {
    const infrastructure = typeof clubInfrastructurePlayerXpMultiplier === 'function' ? clubInfrastructurePlayerXpMultiplier() : 1;
    return (1 + teamBenefitLevel('analysis') * 0.06) * infrastructure;
  }

  function teamRecoveryBonus() {
    const infrastructure = typeof clubInfrastructureFatigueRecoveryBonus === 'function' ? clubInfrastructureFatigueRecoveryBonus() : 0;
    return teamBenefitLevel('recovery') * 2 + infrastructure;
  }

  function teamCommercialIncomeMultiplier() {
    const infrastructure = typeof clubInfrastructureMatchIncomeMultiplier === 'function' ? clubInfrastructureMatchIncomeMultiplier() : 1;
    return (1 + teamBenefitLevel('commercial') * 0.04) * infrastructure;
  }

  function playerXpRequired(playerOrLevel = 1) {
    const level = typeof playerOrLevel === 'object'
      ? Math.max(1, Math.round(Number(playerOrLevel?.level) || 1))
      : Math.max(1, Math.round(Number(playerOrLevel) || 1));
    return PLAYER_XP_BASE + Math.max(0, level - 1) * PLAYER_XP_GROWTH;
  }

  function playerTrainingProgressTemplate(raw = null) {
    return Object.fromEntries(Object.keys(CAREER_STAT_DEFS).map(key => [
      key,
      clamp(Number(raw?.[key]) || 0, 0, TRAINING_PROGRESS_TARGET - 0.001)
    ]));
  }

  function normalisePlayerDevelopment(player) {
    if (!player || typeof player !== 'object') return player;
    player.level = Math.max(1, Math.round(Number(player.level) || 1));
    player.xp = Math.max(0, Math.round(Number(player.xp) || 0));
    player.unspentPoints = Math.max(0, Math.round(Number(player.unspentPoints) || 0));
    player.trainingFocus = TRAINING_FOCUS_DEFS[player.trainingFocus] ? player.trainingFocus : 'none';
    player.trainingProgress = playerTrainingProgressTemplate(player.trainingProgress);
    player.trainingLastGain = Math.max(0, Number(player.trainingLastGain) || 0);
    player.trainingLastResult = String(player.trainingLastResult || 'No completed training day recorded.');
    player.transferInterest = player.transferInterest && typeof player.transferInterest === 'object'
      ? {
          score: clamp(Math.round(Number(player.transferInterest.score) || 0), 0, 100),
          label: String(player.transferInterest.label || 'Limited Interest'),
          clubs: Array.isArray(player.transferInterest.clubs) ? player.transferInterest.clubs.slice(0, 4).map(String) : []
        }
      : { score: 0, label: 'Limited Interest', clubs: [] };
    return player;
  }

  function playerCanDevelop(player) {
    if (!player) return false;
    if (Object.values(player.stats || {}).every(value => Number(value) >= CAREER_MAX_STAT)) return false;
    return teamPlayerOverall(player) < clamp(Number(player.potential) || 0, 0, 100);
  }

  function playerProjectedOverallAfterStat(player, stat) {
    if (!player || !CAREER_STAT_DEFS[stat]) return teamPlayerOverall(player);
    const stats = { ...(player.stats || {}) };
    stats[stat] = clamp(Math.round(Number(stats[stat]) || 0) + 1, 0, CAREER_MAX_STAT);
    return teamPlayerOverall({ ...player, stats });
  }

  function playerCanIncreaseStat(player, stat) {
    if (!player || !CAREER_STAT_DEFS[stat]) return false;
    if (Number(player.stats?.[stat]) >= CAREER_MAX_STAT || !playerCanDevelop(player)) return false;
    return playerProjectedOverallAfterStat(player, stat) <= clamp(Number(player.potential) || 0, 0, 100);
  }

  function playerCanAllocateStat(player, stat) {
    return Boolean(player && Number(player.unspentPoints) > 0 && playerCanIncreaseStat(player, stat));
  }

  function addPlayerXp(player, amount) {
    normalisePlayerDevelopment(player);
    const awarded = Math.max(0, Math.round(Number(amount) || 0));
    let levelsGained = 0;
    player.xp += awarded;
    while (player.xp >= playerXpRequired(player)) {
      player.xp -= playerXpRequired(player);
      player.level++;
      player.unspentPoints++;
      levelsGained++;
    }
    return { awarded, levelsGained };
  }

  function playerMarketValue(player) {
    if (!player) return 0;
    const overall = teamPlayerOverall(player);
    const potential = clamp(Number(player.potential) || overall, 0, 100);
    const age = clamp(Number(player.age) || 24, 17, 40);
    const form = clamp(Number(player.form) || 6.5, 1, 10);
    const recentRating = clamp(Number(player.lastMatch?.rating) || Number(player.career?.rating) || 0, 0, 10);
    const potentialGap = Math.max(0, potential - overall);
    const youthPremium = age <= 23 ? (24 - age) * 8500 : age >= 31 ? -(age - 30) * 7000 : 0;
    const contractMultiplier = clamp(0.78 + Math.min(156, Number(player.contractWeeks) || 0) / 520, 0.78, 1.08);
    const injuryPenalty = typeof playerInjuryPenalty === 'function' ? playerInjuryPenalty(player) : 0;
    const injuryMultiplier = clamp(1 - injuryPenalty * 1.15, 0.82, 1);
    const raw = (
      18000 +
      overall * overall * 58 +
      potential * 760 +
      potentialGap * 1250 +
      form * 3400 +
      recentRating * 2200 +
      Math.max(0, Number(player.level) - 1) * 4200 +
      youthPremium
    ) * contractMultiplier * injuryMultiplier;
    return Math.max(18000, Math.round(raw / 1000) * 1000);
  }

  function playerInterestScore(player) {
    if (!player) return 0;
    const overall = teamPlayerOverall(player);
    const potential = clamp(Number(player.potential) || overall, 0, 100);
    const form = clamp(Number(player.form) || 6.5, 1, 10);
    const recentRating = clamp(Number(player.lastMatch?.rating) || Number(player.career?.rating) || 0, 0, 10);
    const age = clamp(Number(player.age) || 24, 17, 40);
    const ageAdjustment = age <= 22 ? 8 : age <= 27 ? 4 : age >= 33 ? -8 : 0;
    const wagePenalty = Math.max(0, (Number(player.wage) || 0) - 9000) / 1800;
    const injuryPenalty = typeof playerInjuryPenalty === 'function' ? playerInjuryPenalty(player) * 92 : 0;
    return clamp(Math.round(
      overall * 0.48 +
      potential * 0.24 +
      form * 2.2 +
      recentRating * 1.4 +
      ageAdjustment +
      clamp(Number(careerState.reputation) || 0, 0, 100) * 0.05 -
      wagePenalty -
      injuryPenalty
    ), 0, 100);
  }

  function playerInterestLabel(score) {
    const value = clamp(Math.round(Number(score) || 0), 0, 100);
    if (value >= 82) return 'HIGH-DEMAND PLAYER';
    if (value >= 70) return 'STRONG INTEREST';
    if (value >= 58) return 'BEING MONITORED';
    if (value >= 46) return 'SOME INTEREST';
    return 'LIMITED INTEREST';
  }

  function playerInterestedClubs(player, score) {
    const candidates = (careerState.league?.clubs || [])
      .filter(club => !club.isUser && club.name && club.id !== careerState.league?.userClubId);
    if (!candidates.length || score < 46) return [];
    const count = score >= 82 ? 3 : score >= 68 ? 2 : 1;
    const random = teamRng(teamSeedFromString(`${player.id}:${careerState.week}:${Math.floor(score / 4)}`));
    const pool = [...candidates];
    const selected = [];
    while (pool.length && selected.length < count) {
      const index = Math.floor(random() * pool.length) % pool.length;
      selected.push(pool.splice(index, 1)[0].name);
    }
    return selected;
  }

  function updatePlayerMarketProfile(player) {
    if (!player) return null;
    normalisePlayerDevelopment(player);
    player.value = playerMarketValue(player);
    const score = playerInterestScore(player);
    player.transferInterest = {
      score,
      label: playerInterestLabel(score),
      clubs: playerInterestedClubs(player, score)
    };
    return player.transferInterest;
  }

  function refreshAllPlayerMarketProfiles() {
    for (const player of careerState.squad || []) updatePlayerMarketProfile(player);
    for (const player of careerState.market || []) updatePlayerMarketProfile(player);
  }

  function playerWithUnspentStatPoints() {
    return (careerState.squad || []).find(player => Math.max(0, Math.round(Number(player?.unspentPoints) || 0)) > 0) || null;
  }

  function playerStatAllocationDraft(playerOrId) {
    const player = typeof playerOrId === 'object'
      ? playerOrId
      : (careerState.squad || []).find(candidate => candidate.id === playerOrId) || null;
    if (!player) return null;
    const raw = playerStatAllocationDrafts.get(player.id);
    if (!raw || typeof raw !== 'object') return null;
    const deltas = {};
    for (const key of Object.keys(CAREER_STAT_DEFS)) {
      const delta = Math.max(0, Math.round(Number(raw.deltas?.[key]) || 0));
      if (delta) deltas[key] = delta;
    }
    const allocated = Object.values(deltas).reduce((sum, value) => sum + value, 0);
    if (!allocated) {
      playerStatAllocationDrafts.delete(player.id);
      return null;
    }
    return { playerId: player.id, deltas, allocated };
  }

  function playerStatAllocationSummary(player) {
    const draft = playerStatAllocationDraft(player);
    const allocated = draft?.allocated || 0;
    const available = Math.max(0, Math.round(Number(player?.unspentPoints) || 0));
    return {
      draft,
      allocated,
      remaining: Math.max(0, available - allocated),
      available,
      hasChanges: allocated > 0
    };
  }

  function playerStatValueWithDraft(player, stat) {
    const base = clamp(Math.round(Number(player?.stats?.[stat]) || 0), 0, CAREER_MAX_STAT);
    const draft = playerStatAllocationDraft(player);
    return clamp(base + Math.max(0, Math.round(Number(draft?.deltas?.[stat]) || 0)), 0, CAREER_MAX_STAT);
  }

  function playerStatsWithDraft(player, extraStat = '', extraDelta = 0) {
    const draft = playerStatAllocationDraft(player);
    return Object.fromEntries(Object.keys(CAREER_STAT_DEFS).map(key => {
      const base = Math.round(Number(player?.stats?.[key]) || 0);
      const pending = Math.max(0, Math.round(Number(draft?.deltas?.[key]) || 0));
      const extra = key === extraStat ? Math.round(Number(extraDelta) || 0) : 0;
      return [key, clamp(base + pending + extra, 0, CAREER_MAX_STAT)];
    }));
  }

  function playerCanDraftStatPoint(player, stat) {
    if (!player || !CAREER_STAT_DEFS[stat] || menuContext === 'pause' || appState === 'match') return false;
    const summary = playerStatAllocationSummary(player);
    if (summary.remaining <= 0 || playerStatValueWithDraft(player, stat) >= CAREER_MAX_STAT) return false;
    const projectedStats = playerStatsWithDraft(player, stat, 1);
    const projectedOverall = teamPlayerOverall({ ...player, stats: projectedStats });
    return projectedOverall <= clamp(Number(player.potential) || 0, 0, 100);
  }

  function changePlayerStatDraft(playerId, stat, delta) {
    if (menuContext === 'pause' || appState === 'match' || !CAREER_STAT_DEFS[stat]) return false;
    const player = (careerState.squad || []).find(candidate => candidate.id === playerId) || null;
    if (!player) return false;
    const current = playerStatAllocationDraft(player) || { playerId: player.id, deltas: {}, allocated: 0 };
    const existing = Math.max(0, Math.round(Number(current.deltas[stat]) || 0));
    if (delta > 0) {
      if (!playerCanDraftStatPoint(player, stat)) return false;
      current.deltas[stat] = existing + 1;
    } else if (delta < 0) {
      if (existing <= 0) return false;
      if (existing === 1) delete current.deltas[stat];
      else current.deltas[stat] = existing - 1;
    } else {
      return false;
    }
    const allocated = Object.values(current.deltas).reduce((sum, value) => sum + Math.max(0, Math.round(Number(value) || 0)), 0);
    if (allocated) playerStatAllocationDrafts.set(player.id, { playerId: player.id, deltas: { ...current.deltas } });
    else playerStatAllocationDrafts.delete(player.id);
    updateMenuUI();
    return true;
  }

  function resetPlayerStatDraft(playerId, render = true) {
    const removed = playerStatAllocationDrafts.delete(String(playerId || ''));
    if (removed && render) updateMenuUI();
    return removed;
  }

  function savePlayerStatDraft(playerId) {
    if (menuContext === 'pause' || appState === 'match') return false;
    const player = (careerState.squad || []).find(candidate => candidate.id === playerId) || null;
    const draft = playerStatAllocationDraft(player);
    if (!player || !draft || draft.allocated <= 0 || draft.allocated > Math.max(0, Number(player.unspentPoints) || 0)) return false;
    const finalStats = playerStatsWithDraft(player);
    if (Object.values(finalStats).some(value => value > CAREER_MAX_STAT)) return false;
    if (teamPlayerOverall({ ...player, stats: finalStats }) > clamp(Number(player.potential) || 0, 0, 100)) return false;
    player.stats = finalStats;
    player.unspentPoints = Math.max(0, Math.round(Number(player.unspentPoints) || 0) - draft.allocated);
    playerStatAllocationDrafts.delete(player.id);
    updatePlayerMarketProfile(player);
    saveCareerState();
    updateMenuUI();
    return true;
  }

  function renderPlayerStatPointBanner(player) {
    if (!player) return '';
    const summary = playerStatAllocationSummary(player);
    if (!summary.available && !summary.hasChanges) return '';
    const headline = summary.hasChanges
      ? `${summary.allocated} POINT${summary.allocated === 1 ? '' : 'S'} PENDING · ${summary.remaining} REMAINING`
      : `${summary.available} STAT POINT${summary.available === 1 ? '' : 'S'} AVAILABLE`;
    return `<div class="player-stat-point-banner ${summary.hasChanges ? 'pending' : ''}" data-player-stat-card="${escapeCareerHtml(player.id)}"><div><span>${summary.hasChanges ? 'UNSAVED ATTRIBUTE CHANGES' : 'STAT POINT AVAILABLE'}</span><strong>${headline}</strong><small>Use + and − to test an allocation. Attributes are not permanent until Save Changes is selected.</small></div></div>`;
  }

  function renderPlayerStatAllocationActions(player) {
    if (!player) return '';
    const summary = playerStatAllocationSummary(player);
    return `<div class="player-stat-allocation-actions"><span>${summary.hasChanges ? `${summary.allocated} pending · ${summary.remaining} unallocated` : 'No unsaved changes'}</span><button data-player-stat-reset="${escapeCareerHtml(player.id)}" ${summary.hasChanges ? '' : 'disabled'}>REMOVE CHANGES</button><button class="primary" data-player-stat-save="${escapeCareerHtml(player.id)}" ${summary.hasChanges ? '' : 'disabled'}>SAVE CHANGES</button></div>`;
  }

  function allocatePlayerStatPoint(playerId, stat) {
    if (menuContext === 'pause' || appState === 'match') return false;
    const player = (careerState.squad || []).find(candidate => candidate.id === playerId) || null;
    if (!playerCanAllocateStat(player, stat)) return false;
    player.stats[stat] = clamp(Math.round(Number(player.stats[stat]) || 0) + 1, 0, CAREER_MAX_STAT);
    player.unspentPoints--;
    updatePlayerMarketProfile(player);
    saveCareerState();
    updateMenuUI();
    return true;
  }

  function allocateTeamBenefit(id) {
    if (menuContext === 'pause' || appState === 'match') return false;
    if (!TEAM_BENEFIT_DEFS[id] || careerState.unspentPoints <= 0) return false;
    const level = teamBenefitLevel(id);
    if (level >= TEAM_BENEFIT_MAX) return false;
    careerState.teamBenefits[id] = level + 1;
    careerState.unspentPoints--;
    saveCareerState();
    updateMenuUI();
    return true;
  }

  function setPlayerTrainingFocus(playerId, focus, options = {}) {
    if (menuContext === 'pause' || appState === 'match') return false;
    const player = (careerState.squad || []).find(candidate => candidate.id === playerId) || null;
    if (!player || !TRAINING_FOCUS_DEFS[focus]) return false;
    normalisePlayerDevelopment(player);
    player.trainingFocus = focus;
    player.trainingLastResult = focus === 'none'
      ? 'No assignment selected. Extra recovery applies whenever the calendar advances.'
      : focus === 'recovery'
        ? 'Recovery programme selected. Medical and fatigue recovery advance with each simulated day.'
        : `${TRAINING_FOCUS_DEFS[focus].label} selected. Progress is added gradually with each simulated day.`;
    if (options.save !== false) saveCareerState();
    if (options.render !== false) updateMenuUI();
    return true;
  }

  function playerTrainingGain(player) {
    const age = clamp(Number(player.age) || 24, 17, 40);
    const potentialGap = Math.max(0, (Number(player.potential) || 0) - teamPlayerOverall(player));
    const ageMultiplier = age <= 20 ? 1.20 : age <= 24 ? 1.10 : age >= 32 ? 0.80 : age >= 29 ? 0.90 : 1;
    const potentialMultiplier = 1 + clamp(potentialGap / 110, 0, 0.24);
    const fatigueMultiplier = Number(player.fatigue) >= 82 ? 0.70 : Number(player.fatigue) >= 65 ? 0.84 : 1;
    const dynamicsMultiplier = typeof squadDynamicsDevelopmentMultiplier === 'function' ? squadDynamicsDevelopmentMultiplier(player) : 1;
    return 15 * teamTrainingMultiplier() * ageMultiplier * potentialMultiplier * fatigueMultiplier * dynamicsMultiplier;
  }

  function applyPlayerTrainingDay(player, dayOfWeek = null) {
    normalisePlayerDevelopment(player);
    const focus = player.trainingFocus;
    const currentDay = Number.isFinite(Number(dayOfWeek))
      ? clamp(Math.round(Number(dayOfWeek)), 0, 6)
      : (typeof clubCalendarState === 'function' ? clubCalendarState().dayOfWeek : 0);
    const sciencePerDay = teamRecoveryBonus() / 7;
    player.dailyRecoveryAccumulator = Math.max(0, Number(player.dailyRecoveryAccumulator) || 0) + sciencePerDay;
    const scienceWhole = Math.floor(player.dailyRecoveryAccumulator);
    player.dailyRecoveryAccumulator -= scienceWhole;

    if (focus === 'none') {
      const recovered = 2 + scienceWhole;
      player.fatigue = clamp(Math.round(player.fatigue - recovered), 0, 100);
      player.trainingLastGain = 0;
      player.trainingLastResult = `Unassigned day · ${recovered}% fatigue recovered.`;
      return { focus, progress: 0, statGained: null, recovered, day: currentDay };
    }
    if (focus === 'recovery') {
      const recovered = 4 + scienceWhole;
      player.fatigue = clamp(Math.round(player.fatigue - recovered), 0, 100);
      player.happiness = clamp(Math.round(player.happiness + (currentDay === 6 ? 1 : 0)), 1, 100);
      player.trainingLastGain = 0;
      player.trainingLastResult = `Recovery day · ${recovered}% fatigue recovered.`;
      return { focus, progress: 0, statGained: null, recovered, day: currentDay };
    }

    const gain = playerTrainingGain(player) / 7;
    const scheduledLoad = [1, 3, 5].includes(currentDay) ? 1 : 0;
    const recovered = Math.max(0, 1 + scienceWhole - scheduledLoad);
    player.fatigue = clamp(Math.round(player.fatigue - recovered), 0, 100);
    player.trainingLastGain = Number(gain.toFixed(1));
    if (!playerCanIncreaseStat(player, focus)) {
      player.trainingLastResult = `${TRAINING_FOCUS_DEFS[focus].label} · development ceiling reached.`;
      return { focus, progress: 0, statGained: null, ceiling: true, recovered, day: currentDay };
    }

    player.trainingProgress[focus] = clamp(Number(player.trainingProgress[focus]) + gain, 0, 199.999);
    let statGained = null;
    if (player.trainingProgress[focus] >= TRAINING_PROGRESS_TARGET && playerCanIncreaseStat(player, focus)) {
      player.trainingProgress[focus] -= TRAINING_PROGRESS_TARGET;
      player.stats[focus] = clamp(Math.round(Number(player.stats[focus]) || 0) + 1, 0, CAREER_MAX_STAT);
      statGained = focus;
      updatePlayerMarketProfile(player);
    }
    player.trainingLastResult = statGained
      ? `${TRAINING_FOCUS_DEFS[focus].label} completed · ${CAREER_STAT_DEFS[focus].label} increased to ${player.stats[focus]}.`
      : `${TRAINING_FOCUS_DEFS[focus].label} · +${gain.toFixed(1)} daily development progress.`;
    return { focus, progress: gain, statGained, recovered, day: currentDay };
  }

  function applyPlayerTrainingWeek(player) {
    normalisePlayerDevelopment(player);
    const focus = player.trainingFocus;
    const recovery = teamRecoveryBonus();
    if (focus === 'none') {
      player.fatigue = clamp(Math.round(player.fatigue - 4 - recovery), 0, 100);
      player.trainingLastGain = 0;
      player.trainingLastResult = `Unassigned week · ${4 + recovery}% additional fatigue recovered.`;
      return { focus, progress: 0, statGained: null, recovered: 4 + recovery };
    }
    if (focus === 'recovery') {
      const recovered = 14 + recovery;
      player.fatigue = clamp(Math.round(player.fatigue - recovered), 0, 100);
      player.happiness = clamp(Math.round(player.happiness + 1), 1, 100);
      player.trainingLastGain = 0;
      player.trainingLastResult = `Recovery programme · ${recovered}% fatigue recovered.`;
      return { focus, progress: 0, statGained: null, recovered };
    }

    const gain = playerTrainingGain(player);
    player.trainingLastGain = Number(gain.toFixed(1));
    player.fatigue = clamp(Math.round(player.fatigue + 3 - recovery), 0, 100);
    if (!playerCanIncreaseStat(player, focus)) {
      player.trainingLastResult = `${TRAINING_FOCUS_DEFS[focus].label} · development ceiling reached.`;
      return { focus, progress: 0, statGained: null, ceiling: true };
    }

    player.trainingProgress[focus] = clamp(Number(player.trainingProgress[focus]) + gain, 0, 199.999);
    let statGained = null;
    if (player.trainingProgress[focus] >= TRAINING_PROGRESS_TARGET && playerCanIncreaseStat(player, focus)) {
      player.trainingProgress[focus] -= TRAINING_PROGRESS_TARGET;
      player.stats[focus] = clamp(Math.round(Number(player.stats[focus]) || 0) + 1, 0, CAREER_MAX_STAT);
      statGained = focus;
      updatePlayerMarketProfile(player);
    }
    player.trainingLastResult = statGained
      ? `${TRAINING_FOCUS_DEFS[focus].label} completed · ${CAREER_STAT_DEFS[focus].label} increased to ${player.stats[focus]}.`
      : `${TRAINING_FOCUS_DEFS[focus].label} · +${gain.toFixed(1)} development progress.`;
    return { focus, progress: gain, statGained, recovered: recovery };
  }

  function settlePlayerDevelopmentAfterMatch(player, performance, started, won) {
    normalisePlayerDevelopment(player);
    const rating = clamp(Number(performance?.rating) || 0, 0, 10);
    const kills = Math.max(0, Math.round(Number(performance?.kills) || 0));
    const rounds = Math.max(0, Math.round(Number(performance?.rounds) || 0));
    const rawXp = started
      ? 26 + kills * 5 + Math.round(rating * 7) + rounds * 2 + (won ? 16 : 0)
      : 9;
    const dynamicsMultiplier = typeof squadDynamicsDevelopmentMultiplier === 'function' ? squadDynamicsDevelopmentMultiplier(player) : 1;
    const xpResult = addPlayerXp(player, Math.round(rawXp * teamPlayerXpMultiplier() * dynamicsMultiplier));
    if (player.lastMatch && started) {
      player.lastMatch.playerXpAward = xpResult.awarded;
      player.lastMatch.playerLevelsGained = xpResult.levelsGained;
    }
    updatePlayerMarketProfile(player);
    return { playerId: player.id, xp: xpResult.awarded, levelsGained: xpResult.levelsGained, training: null };
  }

