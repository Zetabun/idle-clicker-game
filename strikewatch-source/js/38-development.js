  function goldCoinAccountSummary() {
    const history = Array.isArray(careerState.goldCoinHistory) ? careerState.goldCoinHistory : [];
    const earned = history.filter(item => Number(item.amount) > 0).reduce((sum, item) => sum + Number(item.amount || 0), 0);
    const spent = Math.abs(history.filter(item => Number(item.amount) < 0).reduce((sum, item) => sum + Number(item.amount || 0), 0));
    const matchIncome = history.filter(item => item.type === 'match' && Number(item.amount) > 0).reduce((sum, item) => sum + Number(item.amount || 0), 0);
    const leagueIncome = history.filter(item => item.type === 'match' && item.mode === 'league').reduce((sum, item) => sum + Math.max(0, Number(item.amount) || 0), 0);
    const exhibitionIncome = history.filter(item => item.type === 'match' && item.mode !== 'league').reduce((sum, item) => sum + Math.max(0, Number(item.amount) || 0), 0);
    const wins = history.filter(item => item.type === 'match' && item.won === true).length;
    const losses = history.filter(item => item.type === 'match' && item.won === false).length;
    const matchEntries = history.filter(item => item.type === 'match' && Number(item.amount) > 0);
    const averageMatch = matchEntries.length ? Math.round(matchIncome / matchEntries.length) : 0;
    return { history, earned, spent, matchIncome, leagueIncome, exhibitionIncome, wins, losses, matchEntries, averageMatch };
  }

